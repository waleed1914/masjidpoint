// Regenerates the type-floor section of public/css/mobile.css.
//
//   node scripts/build-mobile-type-floor.js
//
// The platform is designed dense — 7px labels, 8px table headers, badges at 7px. That is legible
// on a monitor and is not on a phone. Rather than keep a hand-written list of everything that
// needs raising (which would go stale the moment someone adds a stylesheet), this reads every
// stylesheet, finds each rule that sets text below 11px, and re-emits that same selector at a
// readable size inside mobile.css's phone media query.
//
// Reusing the original selector matters: the override lands in exactly the scope the small size
// was set in, so nothing else on the page changes size as a side effect.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const cssDir = path.join(root, 'public', 'css');
const target = path.join(cssDir, 'mobile.css');
const START = '  /* TYPE-FLOOR-START — generated by scripts/build-mobile-type-floor.js */';
const END = '  /* TYPE-FLOOR-END */';

// Where each source size lands. Small things stay comparatively small: the point is to clear the
// legibility floor, not to flatten the type hierarchy into one size.
const floorFor = px => (px < 9 ? 11 : px < 10 ? 11.5 : 12);

// Brace-depth walk so each rule's enclosing at-rule is known. A rule that only applies at a wider
// breakpoint, or in print, must not be dragged into the phone layer.
function rules(css) {
  const out = [];
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  const stack = [];
  while (i < clean.length) {
    const open = clean.indexOf('{', i);
    if (open === -1) break;
    const close = clean.indexOf('}', open);
    const nextOpen = clean.indexOf('{', open + 1);
    const prelude = clean.slice(i, open).trim().replace(/\s+/g, ' ');
    if (nextOpen !== -1 && nextOpen < close) { stack.push(prelude); i = open + 1; continue; }
    if (close === -1) break;
    out.push({ selector: prelude, body: clean.slice(open + 1, close), media: stack.join(' ') });
    i = close + 1;
    while (stack.length && clean[i] === '}') { stack.pop(); i++; }
    while (i < clean.length && /\s/.test(clean[i])) i++;
  }
  return out;
}

// Some links hide their own label on a phone with font-size:0 and show a shorter one through
// ::after. Giving those a readable size would un-hide the long label and the page would show both,
// so they are collected first and then left alone.
const labelHiding = new Set();
for (const file of fs.readdirSync(cssDir).filter(f => f.endsWith('.css') && f !== 'mobile.css')) {
  for (const rule of rules(fs.readFileSync(path.join(cssDir, file), 'utf8'))) {
    if (!/font-size\s*:\s*0(px)?\s*(;|$)/.test(rule.body)) continue;
    for (const sel of rule.selector.split(',').map(s => s.trim())) labelHiding.add(sel.replace(/::?(after|before)$/, ''));
  }
}

const smallest = new Map();
let scanned = 0;
for (const file of fs.readdirSync(cssDir).filter(f => f.endsWith('.css') && f !== 'mobile.css')) {
  for (const rule of rules(fs.readFileSync(path.join(cssDir, file), 'utf8'))) {
    const match = rule.body.match(/font-size\s*:\s*([\d.]+)px/);
    if (!match) continue;
    scanned++;
    const px = parseFloat(match[1]);
    // 0px is the deliberate "hide the label, show a shorter one via ::after" trick, not a mistake.
    if (px >= 11 || px === 0) continue;
    if (rule.media && !/max-width/.test(rule.media)) continue;
    if (/print|min-width/.test(rule.media)) continue;
    if (!rule.selector || rule.selector.startsWith('@') || rule.selector.includes('%')) continue;
    for (const sel of rule.selector.split(',').map(s => s.trim()).filter(Boolean)) {
      if (labelHiding.has(sel)) continue;
      if (!smallest.has(sel) || smallest.get(sel) > px) smallest.set(sel, px);
    }
  }
}

const groups = {};
for (const [sel, px] of smallest) (groups[floorFor(px)] ||= []).push(sel);

let block = `${START}\n  /* ${smallest.size} selectors that set text below 11px, raised to a readable size. */\n\n`;
for (const size of Object.keys(groups).sort((a, b) => a - b)) {
  block += `  ${groups[size].sort().join(',\n  ')} { font-size: ${size}px !important }\n\n`;
}
block += END;

const css = fs.readFileSync(target, 'utf8');
const from = css.indexOf(START.split('—')[0].trimEnd());
const to = css.indexOf(END);
if (from === -1 || to === -1) {
  console.error(`Could not find the TYPE-FLOOR markers in ${path.relative(root, target)}.`);
  process.exit(1);
}
fs.writeFileSync(target, css.slice(0, from) + block + css.slice(to + END.length), 'utf8');

console.log(`Scanned ${scanned} font-size rules across ${fs.readdirSync(cssDir).length - 1} stylesheets.`);
console.log(`Raised ${smallest.size} selectors:`);
for (const size of Object.keys(groups).sort((a, b) => a - b)) console.log(`  ${String(groups[size].length).padStart(3)} -> ${size}px`);
